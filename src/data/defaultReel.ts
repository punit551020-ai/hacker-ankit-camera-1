export function getPresetScenes(
  preset: ReelPresetId,
  lang: 'hinglish' | 'english'
): { scenes: ReelScene[]; appTitle: string; appDownloadUrl: string } {
  if (preset === 'clock-app') {
    return {
      scenes: lang === 'english' ? CLOCK_SCENES_ENGLISH : CLOCK_SCENES_HINGLISH,
      appTitle: 'Hacker Ankit Clock App',
      appDownloadUrl: DEFAULT_CLOCK_APP_URL,
    };
  }
  if (preset === 'calculator-app') {
    return {
      scenes: lang === 'english' ? DEFAULT_SCENES_ENGLISH : DEFAULT_SCENES_HINGLISH,
      appTitle: 'Hacker Ankit Calculator App',
      appDownloadUrl: LIVE_CALCULATOR_URL,
    };
  }
  return {
    scenes: DUAL_SUITE_SCENES_HINGLISH,
    appTitle: 'Hacker Ankit Clock & Calculator Apps',
    appDownloadUrl: DEFAULT_CLOCK_APP_URL,
  };
}
